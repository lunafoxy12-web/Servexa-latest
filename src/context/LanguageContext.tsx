interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (code: LanguageCode) => void;
  currentLanguageInfo: LanguageInfo;
  availableLanguages: LanguageInfo[];
  t: (key: string, defaultText?: string) => string;
  isRTL: boolean;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    try {
      const saved = localStorage.getItem('servexa_language') as LanguageCode;
      if (saved && AVAILABLE_LANGUAGES.some((l) => l.code === saved)) {
        return saved;
      }
      // Check browser language
      if (typeof navigator !== 'undefined' && navigator.language) {
        const browserCode = navigator.language.slice(0, 2).toLowerCase() as LanguageCode;
        if (AVAILABLE_LANGUAGES.some((l) => l.code === browserCode)) {
          return browserCode;
        }
      }
    } catch {
      // fallback
    }
    return 'en';
  });

  const currentLanguageInfo =
    AVAILABLE_LANGUAGES.find((l) => l.code === language) || AVAILABLE_LANGUAGES[0];

  const isRTL = currentLanguageInfo.dir === 'rtl';

  const setLanguage = useCallback((code: LanguageCode) => {
    if (AVAILABLE_LANGUAGES.some((l) => l.code === code)) {
      setLanguageState(code);
      try {
        localStorage.setItem('servexa_language', code);
      } catch {
        // ignore
      }
    }
  }, []);

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = language;
      document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
      document.body.setAttribute('data-lang', language);
    }
  }, [language, isRTL]);

  const t = useCallback(
    (key: string, defaultText?: string): string => {
      const langDict = TRANSLATIONS[language] || TRANSLATIONS['en'];
      if (langDict && langDict[key]) {
        return langDict[key];
      }
      const fallbackDict = TRANSLATIONS['en'];
      if (fallbackDict && fallbackDict[key]) {
        return fallbackDict[key];
      }
      return defaultText !== undefined ? defaultText : key;
    },
    [language]
  );

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        currentLanguageInfo,
        availableLanguages: AVAILABLE_LANGUAGES,
        t,
        isRTL
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
